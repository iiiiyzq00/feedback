CREATE TABLE t_rca_orchestration_task (
  id BIGINT NOT NULL AUTO_INCREMENT,
  task_key VARCHAR(160) NOT NULL,
  request_snapshot JSON NOT NULL,
  trigger_type VARCHAR(20) NOT NULL,
  task_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  current_step VARCHAR(30) NOT NULL DEFAULT 'FACTS',
  retry_count INT NOT NULL DEFAULT 0,
  max_retries INT NOT NULL DEFAULT 5,
  next_retry_at DATETIME(3) DEFAULT NULL,
  lease_owner VARCHAR(100) DEFAULT NULL,
  lease_until DATETIME(3) DEFAULT NULL,
  cancel_requested TINYINT(1) NOT NULL DEFAULT 0,
  result_rca_id BIGINT DEFAULT NULL,
  error_code VARCHAR(100) DEFAULT NULL,
  error_detail VARCHAR(1000) DEFAULT NULL,
  created_by BIGINT DEFAULT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  started_at DATETIME(3) DEFAULT NULL,
  completed_at DATETIME(3) DEFAULT NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_rca_task_key (task_key),
  KEY idx_rca_task_claim (task_status,next_retry_at,lease_until,created_at),
  CONSTRAINT fk_rca_task_result FOREIGN KEY (result_rca_id) REFERENCES t_root_cause_analysis(id),
  CONSTRAINT fk_rca_task_user FOREIGN KEY (created_by) REFERENCES t_auth_user(id),
  CONSTRAINT chk_rca_task_status CHECK (task_status IN ('PENDING','RUNNING','RETRY_PENDING','COMPLETED','FAILED','CANCELLED')),
  CONSTRAINT chk_rca_task_step CHECK (current_step IN ('FACTS','CORRELATION','FIVE_WHYS','IMPACT','PERSIST','DONE')),
  CONSTRAINT chk_rca_task_retry CHECK (retry_count BETWEEN 0 AND max_retries)
) ENGINE=InnoDB COMMENT='深度RCA可续跑编排任务';

CREATE TABLE t_rca_orchestration_step (
  id BIGINT NOT NULL AUTO_INCREMENT,
  task_id BIGINT NOT NULL,
  step_code VARCHAR(30) NOT NULL,
  step_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  attempt_count INT NOT NULL DEFAULT 0,
  input_snapshot JSON DEFAULT NULL,
  output_snapshot JSON DEFAULT NULL,
  output_sha256 BINARY(32) DEFAULT NULL,
  error_code VARCHAR(100) DEFAULT NULL,
  error_detail VARCHAR(1000) DEFAULT NULL,
  started_at DATETIME(3) DEFAULT NULL,
  completed_at DATETIME(3) DEFAULT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_rca_task_step (task_id,step_code),
  CONSTRAINT fk_rca_step_task FOREIGN KEY (task_id) REFERENCES t_rca_orchestration_task(id) ON DELETE CASCADE,
  CONSTRAINT chk_rca_step_status CHECK (step_status IN ('PENDING','RUNNING','COMPLETED','FAILED','CANCELLED'))
) ENGINE=InnoDB COMMENT='深度RCA步骤级输入输出、重试与恢复证据';

