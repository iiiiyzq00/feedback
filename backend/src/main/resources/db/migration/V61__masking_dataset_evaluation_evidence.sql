  ADD CONSTRAINT fk_masking_release_run FOREIGN KEY(evaluation_run_id) REFERENCES t_masking_evaluation_run(id),
  ADD CONSTRAINT fk_masking_release_eval_approver FOREIGN KEY(evaluation_approved_by) REFERENCES t_auth_user(id);

