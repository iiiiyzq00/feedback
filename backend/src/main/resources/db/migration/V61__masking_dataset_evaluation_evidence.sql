CREATE TABLE t_masking_evaluation_dataset (
  id BIGINT NOT NULL AUTO_INCREMENT,
  dataset_version VARCHAR(80) NOT NULL,
  dataset_sha256 CHAR(64) NOT NULL,
  evidence_kind VARCHAR(30) NOT NULL,
  storage_reference VARCHAR(500) NOT NULL,
  sample_count INT NOT NULL,
  positive_count INT NOT NULL,
  negative_count INT NOT NULL,
  boundary_count INT NOT NULL,
  pii_approval_reference VARCHAR(200) DEFAULT NULL,
  dataset_status VARCHAR(20) NOT NULL DEFAULT 'REGISTERED',
  annotated_by BIGINT NOT NULL,
  reviewed_by BIGINT DEFAULT NULL,
  reviewed_at DATETIME(3) DEFAULT NULL,
  approved_by BIGINT DEFAULT NULL,
  approved_at DATETIME(3) DEFAULT NULL,
  expires_at DATETIME(3) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY(id),
  UNIQUE KEY uk_masking_dataset_version(dataset_version),
  UNIQUE KEY uk_masking_dataset_sha(dataset_sha256),
  CONSTRAINT fk_masking_dataset_annotator FOREIGN KEY(annotated_by) REFERENCES t_auth_user(id),
  CONSTRAINT fk_masking_dataset_reviewer FOREIGN KEY(reviewed_by) REFERENCES t_auth_user(id),
  CONSTRAINT fk_masking_dataset_approver FOREIGN KEY(approved_by) REFERENCES t_auth_user(id),
  CONSTRAINT chk_masking_dataset_kind CHECK(evidence_kind IN ('FIXTURE','APPROVED_HISTORICAL')),
  CONSTRAINT chk_masking_dataset_status CHECK(dataset_status IN ('REGISTERED','REVIEWED','APPROVED','REJECTED','EXPIRED')),
  CONSTRAINT chk_masking_dataset_distribution CHECK(sample_count=positive_count+negative_count AND sample_count>=100 AND positive_count>0 AND negative_count>0 AND boundary_count BETWEEN 0 AND sample_count)
) ENGINE=InnoDB COMMENT='脱敏评估集只保存指纹、分布和审批，不保存样本原文';

CREATE TABLE t_masking_evaluation_run (
  id BIGINT NOT NULL AUTO_INCREMENT,
  release_id BIGINT NOT NULL,
  dataset_id BIGINT NOT NULL,
  engine_version VARCHAR(100) NOT NULL,
  run_status VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',
  ner_tp INT NOT NULL, ner_fp INT NOT NULL, ner_fn INT NOT NULL,
  end_tp INT NOT NULL, end_fp INT NOT NULL, end_fn INT NOT NULL,
  high_risk_total INT NOT NULL, high_risk_missed INT NOT NULL,
  negative_units INT NOT NULL, false_masked_units INT NOT NULL,
  ner_f1 DECIMAL(7,6) NOT NULL,
  end_to_end_f1 DECIMAL(7,6) NOT NULL,
  high_risk_recall DECIMAL(7,6) NOT NULL,
  false_masking_rate DECIMAL(7,6) NOT NULL,
  gate_result VARCHAR(20) NOT NULL,
  execution_log_sha256 CHAR(64) NOT NULL,
  failure_summary JSON NOT NULL,
  failure_summary_sha256 CHAR(64) NOT NULL,
  executed_by BIGINT NOT NULL,
  executed_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  approved_by BIGINT DEFAULT NULL,
  approved_at DATETIME(3) DEFAULT NULL,
  approval_reason VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY(id),
  UNIQUE KEY uk_masking_release_dataset_engine(release_id,dataset_id,engine_version),
  CONSTRAINT fk_masking_run_release FOREIGN KEY(release_id) REFERENCES t_masking_rule_release(id),
  CONSTRAINT fk_masking_run_dataset FOREIGN KEY(dataset_id) REFERENCES t_masking_evaluation_dataset(id),
  CONSTRAINT fk_masking_run_executor FOREIGN KEY(executed_by) REFERENCES t_auth_user(id),
  CONSTRAINT fk_masking_run_approver FOREIGN KEY(approved_by) REFERENCES t_auth_user(id),
  CONSTRAINT chk_masking_run_status CHECK(run_status IN ('COMPLETED','APPROVED','REJECTED')),
  CONSTRAINT chk_masking_run_gate CHECK(gate_result IN ('PASSED','FAILED')),
  CONSTRAINT chk_masking_run_counts CHECK(ner_tp>=0 AND ner_fp>=0 AND ner_fn>=0 AND end_tp>=0 AND end_fp>=0 AND end_fn>=0 AND high_risk_total>0 AND high_risk_missed BETWEEN 0 AND high_risk_total AND negative_units>0 AND false_masked_units BETWEEN 0 AND negative_units)
) ENGINE=InnoDB COMMENT='脱敏评估可复算计数、指标、日志与安全失败摘要';

ALTER TABLE t_masking_rule_release
  ADD COLUMN evaluation_run_id BIGINT DEFAULT NULL AFTER evaluation_audit_id,
