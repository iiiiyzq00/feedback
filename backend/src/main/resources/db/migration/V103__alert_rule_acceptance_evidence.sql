CREATE TABLE t_alert_rule_acceptance_assessment (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  rule_id BIGINT NOT NULL,
  replay_run_id BIGINT NOT NULL,
  drill_id BIGINT NOT NULL,
  true_positive BIGINT NOT NULL,
  false_positive BIGINT NOT NULL,
  false_negative BIGINT NOT NULL,
  true_negative BIGINT NOT NULL,
  precision_rate DECIMAL(7,6) NOT NULL,
  recall_rate DECIMAL(7,6) NOT NULL,
  routing_outcome VARCHAR(20) NOT NULL,
  evidence_sha256 CHAR(64) NOT NULL,
  assessment_status VARCHAR(20) NOT NULL DEFAULT 'VALIDATED',
  assessed_by BIGINT NOT NULL,
  assessed_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  approved_by BIGINT DEFAULT NULL,
  approved_at DATETIME(3) DEFAULT NULL,
  UNIQUE KEY uk_rule_acceptance_evidence(rule_id,evidence_sha256),
  KEY idx_rule_acceptance_status(rule_id,assessment_status),
  CONSTRAINT chk_rule_acceptance_counts CHECK(true_positive>=0 AND false_positive>=0 AND false_negative>=0 AND true_negative>=0),
  CONSTRAINT chk_rule_acceptance_rates CHECK(precision_rate BETWEEN 0 AND 1 AND recall_rate BETWEEN 0 AND 1),
  CONSTRAINT chk_rule_acceptance_route CHECK(routing_outcome IN ('PASSED','FAILED')),
  CONSTRAINT chk_rule_acceptance_status CHECK(assessment_status IN ('VALIDATED','APPROVED','REJECTED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='规则回放误报漏报与路由演练独立验收证据';
