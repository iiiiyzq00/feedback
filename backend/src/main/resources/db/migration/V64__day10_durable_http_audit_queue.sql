CREATE TABLE t_http_audit_queue (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  actor_id BIGINT NULL,
  operation VARCHAR(50) NOT NULL,
  audit_class VARCHAR(20) NOT NULL,
  outcome VARCHAR(20) NOT NULL,
  target_type VARCHAR(50) NOT NULL,
  target_id VARCHAR(100) NULL,
  request_id VARCHAR(64) NOT NULL,
  client_ip VARCHAR(50) NULL,
  event_detail JSON NOT NULL,
  task_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  retry_count INT NOT NULL DEFAULT 0,
  next_retry_at DATETIME(3) NULL,
  lease_holder VARCHAR(100) NULL,
  lease_expires_at DATETIME(3) NULL,
  error_detail VARCHAR(500) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  completed_at DATETIME(3) NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_http_audit_request (request_id),
  KEY idx_http_audit_worker (task_status,next_retry_at,lease_expires_at,id),
  CONSTRAINT chk_http_audit_status CHECK (task_status IN ('PENDING','PROCESSING','RETRY_PENDING','COMPLETED','FAILED')),
  CONSTRAINT chk_http_audit_retry CHECK (retry_count BETWEEN 0 AND 10)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
