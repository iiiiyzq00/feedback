CREATE TABLE t_jira_sync_state (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  connection_key VARCHAR(50) NOT NULL,
  source_instance_hash BINARY(32) NOT NULL,
  sync_status VARCHAR(20) NOT NULL DEFAULT 'DISABLED',
  watermark_updated_at DATETIME(3) DEFAULT NULL,
  requested_window_from DATETIME(3) DEFAULT NULL,
  requested_window_to DATETIME(3) DEFAULT NULL,
  requested_trigger VARCHAR(20) DEFAULT NULL,
  requested_by BIGINT DEFAULT NULL,
  last_attempt_at DATETIME(3) DEFAULT NULL,
  last_success_at DATETIME(3) DEFAULT NULL,
  last_batch_id BIGINT DEFAULT NULL,
  next_run_at DATETIME(3) DEFAULT NULL,
  lease_holder VARCHAR(100) DEFAULT NULL,
  lease_expires_at DATETIME(3) DEFAULT NULL,
  failure_count INT NOT NULL DEFAULT 0,
  last_error_code VARCHAR(50) DEFAULT NULL,
  last_error_detail VARCHAR(500) DEFAULT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT uk_jira_sync_connection UNIQUE (connection_key),
  CONSTRAINT chk_jira_sync_status CHECK (sync_status IN ('DISABLED','IDLE','QUEUED','RUNNING','FAILED')),
  CONSTRAINT chk_jira_sync_requested_trigger CHECK (requested_trigger IS NULL OR requested_trigger IN ('MANUAL','SCHEDULED','BACKFILL')),
  CONSTRAINT chk_jira_sync_requested_window CHECK (requested_window_from IS NULL OR requested_window_to IS NULL OR requested_window_from <= requested_window_to),
  CONSTRAINT chk_jira_sync_failure_count CHECK (failure_count >= 0),
  KEY idx_jira_sync_due (sync_status, next_run_at, lease_expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='400 Jira只读API同步水位、租约和运行状态；不存储秘密或明文地址';
