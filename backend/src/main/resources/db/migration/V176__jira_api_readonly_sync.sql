ALTER TABLE t_import_batch
  ADD COLUMN ingest_method VARCHAR(10) NOT NULL DEFAULT 'FILE' AFTER source_channel,
  ADD COLUMN trigger_type VARCHAR(20) DEFAULT NULL AFTER ingest_method,
  ADD COLUMN source_instance_hash BINARY(32) DEFAULT NULL AFTER trigger_type,
  ADD COLUMN sync_window_from DATETIME(3) DEFAULT NULL AFTER source_instance_hash,
  ADD COLUMN sync_window_to DATETIME(3) DEFAULT NULL AFTER sync_window_from,
  ADD CONSTRAINT chk_import_ingest_method CHECK (ingest_method IN ('FILE','API')),
  ADD CONSTRAINT chk_import_trigger_type CHECK (trigger_type IS NULL OR trigger_type IN ('MANUAL','SCHEDULED','BACKFILL')),
