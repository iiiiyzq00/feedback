package com.feedback.model.imports

import java.time.LocalDate
import java.time.LocalDateTime

/** 文件导入批次领域快照；批次指纹、版本和计数用于幂等与对账。 */
data class ImportBatch(
    var id: Long = 0,
    val publicId: ByteArray,
    val batchId: String,
    val sourceChannel: String,
    val ingestMethod: String = "FILE",
    val triggerType: String? = null,
    val sourceInstanceHash: ByteArray? = null,
    val syncWindowFrom: LocalDateTime? = null,
    val syncWindowTo: LocalDateTime? = null,
    val originalFilename: String,
    val contentSha256: ByteArray,
    val normalizedContentHash: ByteArray,
    val fileSizeBytes: Long? = null,
    val mappingTemplateId: Long? = null,
    val mappingConfigVersion: String? = null,
    val mappingConfigJson: String? = null,
    val enumMappingVersion: String? = null,
    val enumMappingJson: String? = null,
    val nonemptyHeadersJson: String? = null,
    val totalRows: Int = 0,
    val successRows: Int = 0,
    val insertedRows: Int = 0,
    val updatedRows: Int = 0,
    val failedRows: Int = 0,
    val skippedRows: Int = 0,
    val reviewedRows: Int = 0,
    val reconciliationStatus: String = "PENDING",
    val dataDateFrom: LocalDate? = null,
    val dataDateTo: LocalDate? = null,
    val batchStatus: String = "AWAITING_MAPPING",
    val leaseHolder: String? = null,
    val leaseExpiresAt: LocalDateTime? = null,
    val retryCount: Int = 0,
    val nextRetryAt: LocalDateTime? = null,
    val lastErrorCode: String? = null,
    val lastErrorDetail: String? = null,
    val previousBatchId: Long? = null,
    val governanceStatus: String = "ACTIVE",
    val supersededByBatchId: Long? = null,
    val governanceReason: String? = null,
    val governedAt: LocalDateTime? = null,
    val governedBy: Long? = null,
    val startedAt: LocalDateTime? = null,
    val completedAt: LocalDateTime? = null,
    val createdBy: Long? = null,
    val createdAt: LocalDateTime = LocalDateTime.now(),
    val updatedAt: LocalDateTime = LocalDateTime.now()
)
